/**
 * Turn the lighting-supplier video survey into homepage film cards.
 *
 *   node scripts/build-pooky-films.cjs
 *
 * Reads scripts/pooky-video-scan.json (scripts/scan-site-videos.cjs) and
 * writes src/components/home/pookyFilms.ts.
 *
 * Their site carries very little film: eight embeds across the whole content
 * side, none self-hosted, and none at all on the 400 product pages sampled —
 * the product gallery is rendered client-side, so its videos never appear in
 * the HTML. Those product films are already recorded separately in
 * scripts/pooky-media-scan.json and belong to the products, not to this rail.
 *
 * Of the eight, six are carded. Titles are de-branded the way the rest of the
 * rail is: the supplier's name comes out, and what is left describes the job.
 */
const fs = require("fs");
const path = require("path");

const IN = path.join(__dirname, "pooky-video-scan.json");
const OUT = path.join(__dirname, "..", "src", "components", "home", "pookyFilms.ts");

/**
 * Surveyed but deliberately not carded, with the reason. Named rather than
 * silently dropped so the call is visible.
 */
const EXCLUDED = {
  "vimeo:135572162": "gone — oEmbed answers 404",
  "youtube:PNCwYuXndP0":
    "not the supplier's film. 'The Musical Magic of Busby Berkeley | Warner Archive' " +
    "is a film-archive trailer embedded to illustrate an art-deco blog post; " +
    "carding it would put an unrelated third party's video on our homepage.",
};

/** [label, title] keyed by `<kind>:<id>`. */
const CARDS = {
  "youtube:Wl6D6BV8eEI": ["Lighting design", "How to light a home, with an interior design studio"],
  "vimeo:1172187672": ["Lighting design", "A classic lamp, redrawn"],
  "youtube:OfZcJBWT8K4": ["Lamp care", "Removing a lampshade reducer ring"],
  "youtube:NcOU7KnQxzk": ["Lamp care", "Straightening a lamp ball joint"],
  "youtube:D7NtfI5gqWs": ["Lamp care", "Reattaching a bulb holder"],
  "youtube:7ZgNcwBbNww": ["Lamp care", "Changing a fuse"],
};

const UA = {
  "User-Agent":
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
};

/**
 * maxresdefault only exists for videos uploaded above 720p; asking for one
 * that is not there yields YouTube's grey placeholder rather than a 404, so
 * the card would paint a blank. Checked per id, falling back to hqdefault.
 */
async function ytPoster(id) {
  const max = `https://i.ytimg.com/vi/${id}/maxresdefault.jpg`;
  try {
    const r = await fetch(max, { method: "HEAD", headers: UA });
    if (r.ok) return max;
  } catch {}
  return `https://i.ytimg.com/vi/${id}/hqdefault.jpg`;
}

async function vimeoPoster(id) {
  try {
    const r = await fetch(`https://vimeo.com/api/oembed.json?url=https://vimeo.com/${id}`, {
      headers: UA,
    });
    if (!r.ok) return "";
    return (await r.json()).thumbnail_url || "";
  } catch {
    return "";
  }
}

(async () => {
  const scan = JSON.parse(fs.readFileSync(IN, "utf8"));
  const surveyed = new Set(Object.keys(scan.videos || {}));

  // A surveyed id that is neither carded nor excluded is a gap in the map.
  const unhandled = [...surveyed].filter((k) => !CARDS[k] && !EXCLUDED[k]);
  if (unhandled.length) {
    console.log(`WARN ${unhandled.length} surveyed id(s) neither carded nor excluded:`);
    for (const k of unhandled) console.log("   ", k, "—", (scan.videos[k].pages || [])[0] || "");
  }

  // A carded id missing from the survey means the scan changed under us.
  for (const key of Object.keys(CARDS)) {
    if (!surveyed.has(key)) console.log("NOTE carded id not in this scan:", key);
  }

  const films = [];
  for (const [key, [label, title]] of Object.entries(CARDS)) {
    const [kind, id] = [key.slice(0, key.indexOf(":")), key.slice(key.indexOf(":") + 1)];
    films.push(
      kind === "youtube"
        ? { label, title, youtubeId: id, poster: await ytPoster(id) }
        : { label, title, vimeoId: id, poster: await vimeoPoster(id) },
    );
  }

  const header = `// GENERATED by scripts/build-pooky-films.cjs — do not edit by hand.
// Lighting films surveyed from a supplier site, de-branded, and filtered to
// ids that still play and are actually theirs. The site self-hosts nothing, so
// every card here is an embed. Re-run the build to refresh.
import type { ProjectFilm } from "@/components/home/RealProjects";

export const POOKY_FILMS: ProjectFilm[] = ${JSON.stringify(films, null, 2)};
`;
  fs.writeFileSync(OUT, header);

  const tally = films.reduce((a, f) => {
    const k = f.youtubeId ? "youtube" : "vimeo";
    a[k] = (a[k] || 0) + 1;
    return a;
  }, {});
  console.log(`${films.length} films:`, tally);
  console.log(`excluded: ${Object.keys(EXCLUDED).length}`);
  console.log("->", path.relative(path.join(__dirname, ".."), OUT));
})().catch((e) => {
  console.error(e.stack);
  process.exit(1);
});
